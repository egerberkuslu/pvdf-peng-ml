def tnum(x, d=2, bold=False):
    """Table cell number with a typeset minus sign."""
    if x is None or not np.isfinite(x):
        return "--"
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        if float(s) == 0:
            s = s[1:]
        else:
            s = "$-$" + s[1:]
    return rf"\textbf{{{s}}}" if bold else s


def sig(x, n=3):
    """Round to n significant digits, return a plain string."""
    if x == 0 or not np.isfinite(x):
        return "0"
    xr = float(f"{x:.{n}g}")  # round first so 9.998 -> 10.0 gets the right number of decimals
    d = max(0, n - 1 - int(np.floor(np.log10(abs(xr)))))
    return f"{xr:.{d}f}"


def tsig(x, n=3):
    s = sig(x, n)
    return "$-$" + s[1:] if s.startswith("-") else s


def mnum(x, d=2):
    """Macro value: plain number, negative sign safe in text and math mode."""
    if x is None:
        return "n/a"
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        s = s[1:] if float(s) == 0 else r"\ensuremath{-}" + s[1:]
    return s


def msig(x, n=3):
    s = sig(x, n)
    return r"\ensuremath{-}" + s[1:] if s.startswith("-") else s


def mcond(x, n=2):
    """Condition number: plain integer below 1000, scientific notation from 1000 up."""
    return str(int(round(x))) if x < 1000 else msci(x, n)


def msci(x, n=2):
    return rf"\num{{{x:.{n - 1}e}}}"


class Macros:
    def __init__(self):
        self.lines = []
        self.names = set()

    def add(self, name, value, comment=None):
        full = "phys" + name
        assert re.fullmatch(r"[A-Za-z]+", full), full
        assert full not in self.names, full
        self.names.add(full)
        c = f"  % {comment}" if comment else ""
        self.lines.append(rf"\newcommand{{\{full}}}{{{value}}}{c}")

    def write(self, path):
        hdr = [
            "% numbers_a2.tex: generated by code/a2_physgp.py (task A2); do not edit by hand.",
            "% Source of every value: results/a2_physgp.json (see its index).",
            "% Law coefficients a0, a1, a2 are in mV/N; f0 and gamma in Hz; MAE in V.",
        ]
        with open(path, "w") as fh:
            fh.write("\n".join(hdr + self.lines) + "\n")
        return len(self.lines)


def write_tab(name, body):
    path = os.path.join(TAB, f"tab_phys_{name}.tex")
    with open(path, "w") as fh:
        fh.write(body.strip() + "\n")
    return path


