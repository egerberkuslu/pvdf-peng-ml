def law_marginals(params_list):
    """Law marginals on the design grid for a list of volt-scale parameter vectors."""
    comps_c = np.array([0.0, 0.0, 1.0, 2.0, 3.0])
    forces = np.array([1.0, 2.0, 3.0])
    freqs = np.array([5.0, 10.0, 15.0, 20.0, 25.0])
    fgrid = np.linspace(4.0, 26.0, 221)
    P = np.atleast_2d(params_list)
    out = {"fgrid": fgrid, "freq": [], "force": [], "comp": []}
    for p in P:
        a0, a1, a2, f0, g = p
        comp_fac = a0 + a1 * comps_c + a2 * comps_c**2  # per composition, V/N
        out["freq"].append(comp_fac.mean() * forces.mean() * A.lorentz(fgrid, f0, g))
        out["force"].append(comp_fac.mean() * forces * A.lorentz(freqs, f0, g).mean())
        out["comp"].append(comp_fac * forces.mean() * A.lorentz(freqs, f0, g).mean())
    return {k: np.array(v) if k != "fgrid" else v for k, v in out.items()}


