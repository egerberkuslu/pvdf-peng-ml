def _mv(name, v):
    return v * 1e3 if name in ("a0", "a1", "a2") else v


def on_bound(pn, v):
    """True when f0 or gamma sits on its fit bound (a0-a2 bounds are never active)."""
    j = A.PNAMES.index(pn)
    if j < 3:
        return False
    return abs(v - A.BOUNDS_5[0][j]) < 1e-6 or abs(v - A.BOUNDS_5[1][j]) < 1e-6


def bmark(pn, v):
    c = tsig(_mv(pn, v))
    return c + r"$^{\dagger}$" if on_bound(pn, v) else c


def bound_notes(R):
    """Group-wise fold extremes of f0 and gamma that sit on a bound, per target."""
    out = []
    for t in A.TARGETS:
        I = R["identifiability"][t]
        for pn in ("f0", "gamma"):
            for q in ("min", "max"):
                v = I["group_folds"]["spread"][pn][q]
                if on_bound(pn, v):
                    ax_lv = []
                    for ax, g in I["group_folds"]["per_axis"].items():
                        for lv, val in zip(g["levels"], g["params"][pn]):
                            if abs(val - v) < 1e-9:
                                ax_lv.append((ax, lv))
                    out.append({"target": t, "param": pn, "stat": q, "value": v, "folds": ax_lv})
    return out


